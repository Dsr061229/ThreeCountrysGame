// 平衡常数
// ─────────────────────────────────────────────────────────────

/** 城墙等级上限 */
export const WALL_MAX = 3;

/** 乡勇的底数。另有随户口增长的部分，见 garrisonOf */
export const MILITIA_BASE = 30;

/**
 * 开局的太平日子（日）。头一年没有人会来打玩家的城。
 *
 * 不是为了让游戏变简单，是为了让威胁**可应对**：
 * 兵营要户口二百才解锁，城墙要攒出几百缗钱粮，一级一级修上去还要工期。
 * 整整一年刚好够走完这一遍，也刚好够看完一轮四季。
 * 一个还没学会怎么种田的人被一支流寇灭掉，学不到任何东西。
 */
export const GRACE_DAYS = 360;

/**
 * 新破之城多少日内没人再来碰。
 *
 * 没有这一条，一座边境城会在两家之间来回易主十几次 ——
 * 因为刚打下来的城守军最薄，邻居立刻就能抢回去。
 * 现实里不会这样：得胜之军尚锐，围城的一方也需要时间舔伤口。
 */
export const AFTER_CAPTURE_QUIET = 100;

/**
 * 一座城刚被围过之后，多少日内没人再来。
 *
 * 攻守双方打完一场都要舔伤口。没有这一条，一座边境小县会一年被围三次，
 * 民心永远被摁在个位数，玩家再怎么经营也长不起来 ——
 * 那不是「四战之地的压力」，那是不给活路。
 */
export const AFTER_SIEGE_QUIET = 70;

/** 行军速度：每日推进的千分数（约 6 日一段路） */
export const MARCH_PER_DAY = 170;

/** 军队每人每日耗粮的千分之几石 */
export const ARMY_UPKEEP_PER_1000 = 55;
/**
 * 守在城里的兵，每千人每日吃多少。
 *
 * 比在外头行军的一支要省得多 —— 就地吃、就地补，不必千里转运。
 * 这个数**必须小于城的日产**，否则天下所有的城都在饿肚子：
 * 一开始我按行军的口粮算，结果各城的存粮一路见底，
 * 连主公都发不出粮饷，玩家开局一百六十天就散伙了。
 */
export const CITY_UPKEEP_PER_1000 = 12;
/** 仓廪有底：每一点开发度存得下多少粮 */
export const CITY_GRAIN_PER_DEV = 60;
/**
 * 开发度的上限，按城的规模。
 *
 * `dev` 原先是**没有上限**的：每六天涨一点，十年下来能涨六百 ——
 * 一座小县长成了通都大邑，而它派生的粮、兵也跟着一路虚高
 * （实测各城存粮两万六，守军上万）。
 *
 * 城是有大小的。小县再怎么经营也还是小县。
 */
export const CITY_DEV_PER_SCALE = 30;

/**
 * 守将顶多少事。
 *
 * **`nodeDefence` 原先根本不看守将。**
 * 于是「任命」这套东西 —— 城易主派人、你举荐部将、
 * 乃至主公玩法里最核心的那个动词 —— 在机制上一律是零：
 * 派谁守、派不派人守，城的防御一模一样。
 * 又一条只有数据、没有行为的东西。
 *
 * 现在它是这座城守备的一个乘数：无人主事的兵是散的，
 * 而一位能守的宿将顶得上小半座城墙。
 */
/**
 * 这几个数要**以一为轴**，不能往上加。
 *
 * 头一版写成「底数 950 再按统率加」，寻常守将就有 1.23 ——
 * 等于把天下所有城的防御整体抬高了两成。
 * 后果落在玩家头上：他那座城不吃这一层（他本人就在城里），
 * 于是相对之下成了四邻里最软的一个，流寇提前来、还来得小 ——
 * 「一波比一波强」那条难度曲线当场就平了。
 *
 * 所以：没人守的低于一，寻常守将约等于一，名将高于一。
 */
/** 没人守的城，守备乘这么多（千分数） */
export const WARDEN_NONE = 800;
/** 有人守的底数 */
export const WARDEN_BASE = 760;
/** 统率每一点加多少 */
export const WARDEN_PER_COMMAND = 34;
/** 擅长守备的再加 */
export const WARDEN_GOOD_AT = 120;

/** 连续几季交不上差就会被撤职 */
export const DISMISS_AFTER_MISSES = 3;
