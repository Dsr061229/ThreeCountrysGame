/**
 * 天下的类型 —— 城池网络、势力、部队、围城。
 *
 * 分寸拿捏：**玩家看得见的地方做全，看不见的地方做够**。
 * 玩家亲自治理的城跑完整的地块模型（见 city.ts），
 * 其余几十座城只用一个「发展度 + 粮 + 兵 + 民心」的简化状态自己长。
 * 否则算力全花在没人看的地方，而玩家仍然只看得到一座城。
 */

export type FactionId = string;
export type NodeId = string;
export type ArmyId = string;

// ─────────────────────────────────────────────────────────────
// 势力
// ─────────────────────────────────────────────────────────────

export interface FactionState {
  id: FactionId;
  /** 对其他势力的态度 -100（死仇）~ 100（唇齿） */
  attitude: Record<FactionId, number>;
  /** 出兵冷却（日）。刚打完一仗要缓一缓，不然地图上会全是军队 */
  cooldown: number;
}

// ─────────────────────────────────────────────────────────────
// 城池节点
// ─────────────────────────────────────────────────────────────

export interface CityNode {
  id: NodeId;
  factionId: FactionId;
  /** 发展度。玩家的城由完整模型推导，其余的自己长 */
  dev: number;
  grain: number;
  /** 守军（人） */
  troops: number;
  morale: number;
  /**
   * 新附之地的离心。刚易主时很高，产出打折，也容易再叛。
   * 这是压制主公路线滚雪球的手段之一 —— 打下来不等于吃得下。
   */
  unrest: number;
  /** 上次易主是哪一天。-1 表示开局以来没换过手 */
  takenDay: number;
  /** 上次被围结束在哪一天。-1 表示没被围过 */
  lastSiegeDay: number;
}

// ─────────────────────────────────────────────────────────────
// 部队
// ─────────────────────────────────────────────────────────────

export type ArmyIntent = 'attack' | 'reinforce';

export interface Army {
  id: ArmyId;
  factionId: FactionId;
  troops: number;
  /** 随军口粮。断粮的军队会自己散掉 */
  supply: number;
  fromId: NodeId;
  toId: NodeId;
  /** 行军进度，千分数 0~1000 */
  progress: number;
  intent: ArmyIntent;
  /**
   * 还要走的路（这一程之后的落脚点，末一个是目标）。
   *
   * **远征就是这一串。** 空的就是一程就到 —— 挨着的那种。
   * 有了它，「隔着别人的地界所以过不去」那条死规矩才拆得掉：
   * 兵一程一程地走，每落一次脚散一批人（见 march.ts）。
   */
  route?: NodeId[];
  /** 途中每落一次脚折多少人（千分数）。走得越远越狠 */
  waste?: number;
  /** 这一趟的最终去向。有 route 的时候，toId 只是这一程 */
  finalId?: NodeId;
  /**
   * 带这支兵的是谁。
   *
   * **军功要记到人头上。** 少了它，一个替你连下三城的人
   * 和一个从没出过城的人在账面上一模一样（见 tribute.ts）。
   */
  officerId?: string;
}

/** 围城。攻方抵达之后不是立刻破城，是耗 */
export interface Siege {
  cityId: NodeId;
  factionId: FactionId;
  /** 攻方剩余 */ troops: number;
  supply: number;
  days: number;
  /** 围到第几日发起强攻。流寇耗不起，来了就打 */
  assaultAfter?: number;
  /** 领这一路围城的是谁。破城之日，功记在他头上 */
  officerId?: string;
}

/**
 * 流寇。
 *
 * 不是一家势力，是一种天灾 —— 没有旗号、没有粮道，
 * 饿到一定程度的人拿起刀走到别人的城下。
 *
 * 它的存在是为了填上开局那一年的空白：
 * 太平期里若什么都不发生，玩家会在二十多分钟里只看着数字涨；
 * 而太平期一结束就来一支打不过的正规军，又只会让人莫名其妙地输掉。
 * 流寇给的是**低风险的实战**：输了被抢一笔，不会丢城。
 */
export const BANDIT_ID = 'bandit';
/** 第一股流寇最早在第几日 */
export const BANDIT_FIRST_DAY = 42;
/** 之后每隔多少日再来一股 */
export const BANDIT_INTERVAL = 75;
/** 流寇围到第几日就强攻 */
export const BANDIT_ASSAULT_AFTER = 3;

// ─────────────────────────────────────────────────────────────
// 结局
// ─────────────────────────────────────────────────────────────

/**
 * 这一局怎么收的场。
 *
 * ── 前三条是输法，后三条是主公专有的「盖棺论定」──────────
 *
 * 主公这条线原先**只有输法**：三条全是败，没有一行代码定义过赢。
 * 于是那盘棋的形状是「打到腻了关掉」。
 *
 * 现在他有终点了，而且终点不是胜负屏，是**史书上的一段**：
 * 失败不是「游戏结束」，是「那一段写得不好看」。
 */
export type EndingKind =
  /** 交不上差、失了信任，被撤职 */ | 'dismissed'
  /** 城破被俘 */ | 'captured'
  /** 武将：兵饿散了。主公：地盘丢光，无人肯为之死 */ | 'scattered'
  /** 主公：开国。称了帝，而且基业立得住 */ | 'founded'
  /** 主公：托孤。你没称帝，但你死时的安排立住了 —— 最「三国」的结局 */ | 'entrusted'
  /** 主公：身死业分。你确实做大过，但你一死就散了 */ | 'divided';

export interface Ending {
  kind: EndingKind;
  day: number;
}

