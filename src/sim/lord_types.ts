/**
 * 案头上的一件事。
 *
 * 全部**从天下实况里长出来** —— 这是照抄军令那条硬规矩：
 * 主公不会收到凭空的请求，每一件都能在 state 里指到具体的城、
 * 具体的敌、具体的人。请战的那座敌城是真的挨着他，
 * 请援的那座城是真的正被围。
 */
export type MemorialKind =
  /** 请战 —— 守将看上了隔壁一座敌城 */
  | 'war'
  /** 请粮 —— 城里粮见底了 */
  | 'grain'
  /** 请援 —— 城正被围 */
  | 'relief'
  /** 举荐 —— 有人替你荐一个在野的人 */
  | 'recommend'
  /** 求去 —— 心气跌到底的人请辞 */
  | 'leave'
  /** 来附 —— 一家撑不下去的势力愿举州归附。望高才有人来 */
  | 'submit'
  /**
   * 无人主事 —— 一座城空着，有人自请前往。
   *
   * **这一件是这条线的安全网。**
   * 少了它，一旦守将走光（准了两道辞呈就够），
   * `raiseMemorials` 挨个城找守将、一个也找不到，案头从此永远是空的 ——
   * 玩家除了一遍遍「退朝」什么也做不了。实测就是这么死的。
   *
   * 而且它的形状本来就该是这样：空城这件事**必须有人来告诉你**。
   */
  | 'vacancy'
  /** 劝进 —— 群臣议上尊号。这是「赢」唯一的入口 */
  | 'urge'
  /**
   * 叙功 —— 有人替某某请一个更高的位子。
   *
   * **这是「用人」第一次有了下文。** 一个替你连下三城的人，
   * 和一个丢了两座城的人，从此不再是同一个待遇。
   * 而贬是不用你点的：办砸了自己就掉下去（见 MERIT_DEMOTE）。
   */
  | 'merit'
  /**
   * 露布 —— 前方的战报。
   *
   * **它不要你批，只要你知道。** 案上不该全是要你拍板的事：
   * 一屋子人只在有求于你的时候才出现，那个朝堂是假的。
   * 打赢了要有人来报捷，打输了也得有人来说。
   */
  | 'dispatch';

