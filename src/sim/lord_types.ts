/**
 * 心气的一句话。
 *
 * 玩家永远不能确切知道一个人还剩几分心，只能听他说话的口气。
 * 这是「不做数值面板」最狠的一种用法。
 */
export function heartWord(h: number): string {
  if (h >= 86) return '誓以死报';
  if (h >= 72) return '谢主公信重';
  if (h >= 58) return '奉命唯谨';
  if (h >= 44) return '如常';
  if (h >= 34) return '近来寡言';
  if (h >= 24) return '屡称有疾';
  return '闭门不出';
}

/** 心气的口气档。同一件事，恭、平、硬三种说法 */
export function heartTone(h: number): 'warm' | 'plain' | 'cold' {
  if (h >= 66) return 'warm';
  if (h >= 40) return 'plain';
  return 'cold';
}

/** 望不是数值条，是天下人怎么说你 */
export function renownWord(r: number): string {
  if (r >= 88) return '天下归心';
  if (r >= 74) return '海内称其义';
  if (r >= 60) return '关东多归之';
  if (r >= 46) return '名闻一方';
  if (r >= 32) return '人未深知';
  if (r >= 18) return '颇有訾议';
  return '人谓其鹰视狼顾';
}

/** 「二十日前」这一句 */
export function agoWord(days: number): string {
  if (days <= 0) return '今日';
  if (days === 1) return '昨日';
  if (days < 10) return `${days}日前`;
  if (days < 30) return `${Math.round(days / 5) * 5}日前`;
  return `${Math.floor(days / 30)}月前`;
}
