/**
 * 他听完你的答复，做了什么。
 *
 * **这 0.6 秒是整条线的情绪出口。**
 * `heartWord()` 那句小字写得再好也只是一句小字；
 * 玩家真正会记住的，是「那一次他没有行礼」。
 */
export type Reaction =
  /** 深揖。谢主公 */
  | 'bow_deep'
  /** 抱拳。诺 */
  | 'bow'
  /** 躬身。臣愚昧 —— 心气还在的人，被驳了也还有礼数 */
  | 'stoop'
  /** 略一颔首。敷衍 */
  | 'nod'
  /** 一言不发，转身就走。**不行礼** */
  | 'turn_away'
  /** 「……」 */
  | 'silent';

export const REACTION_SAY: Record<Reaction, string> = {
  bow_deep: '谢主公。',
  bow: '诺。',
  stoop: '臣愚昧。',
  nod: '……是。',
  turn_away: '',
  silent: '……',
};

/** 他这一下算是什么礼数。表现层照这个演 */
export const REACTION_NOTE: Record<Reaction, string> = {
  bow_deep: '深揖而退',
  bow: '抱拳退下',
  stoop: '躬身退下',
  nod: '略一颔首',
  turn_away: '转身就走，没有行礼',
  silent: '半晌无言，退下',
};

/**
 * 心气 + 你的答复 → 他的反应。
 *
 * 规矩只有一条：**礼数是心气的函数，不是答复的函数。**
 * 心气高的人被你驳了也还躬身；心气低的人你允了他，他也只是颔首。
 * 反过来写就成了「你对他好他就对你好」—— 那是个自动贩卖机，不是人。
 */
export function reactionOf(heart: number, answer: Answer, kind: MemorialKind): Reaction {
  if (kind === 'dispatch') return heart >= 44 ? 'bow' : 'nod';
  if (heart < HEART_SILENT) return 'silent';
  if (heart < HEART_QUIET) return answer === 'allow' ? 'nod' : 'turn_away';
  if (heart < 58) return answer === 'allow' ? 'bow' : 'nod';
  if (heart < 72) return answer === 'allow' ? 'bow' : 'stoop';
  return answer === 'allow' ? 'bow_deep' : 'stoop';
}

