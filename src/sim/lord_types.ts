/**
 * 一座营。
 *
 * ── 为什么非要把营和城分开 ──────────────────────────
 *
 * 设计上文武是分职的：**文官占城池，武将有军营。**
 * 但真正逼着我们做这一层的，是一条玩法上的硬伤：
 *
 * **出兵就是掏空守军。** 城里那些人既是守军又是野战军，
 * 你派他们出去打，城就空了；打赢了回来，别人已经摸到你后院。
 * 于是玩家不敢打；不打就不长；不长就等着被人吃掉 ——
 * 推演里那条「前期占几座城，之后一路失守」的曲线，一半来自这里。
 *
 * 分开之后是两笔账：
 *   · **城里的兵守家** —— 不出城，受 `dev × 26` 的顶约束（他们本来就是乡勇）
 *   · **营里的兵野战** —— 脱产，不受那个顶，但**每天要吃粮**
 *
 * 这也正是汉末的实情：郡兵是郡兵，部曲是部曲。
 *
 * ── 一将不能分身 ────────────────────────────────────
 *
 * 一个人要么守一座城，要么领一座营，不能兼。
 * 所以「立几座营」直接受制于你帐下有几个能带兵的人 ——
 * 「城多了管不过来」在这里第三次成立。
 */
export interface Barracks {
  id: string;
  /** 依托哪座城。营在城外几里，粮从这座城出 */
  cityId: NodeId;
  /** 领兵的那位武将 */
  officerId: string;
  troops: number;
  /** 操练 0~100。练得越久，同样的人越能打 */
  drill: number;
  /** 立营那天 */
  since: number;
}

