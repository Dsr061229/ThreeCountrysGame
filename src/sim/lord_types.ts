/**
 * 主公的朝堂。
 *
 * ── 这一层要治的病 ──────────────────────────────────
 *
 * 上一版的主公有四个动词，四个都是**无条件的按钮**：
 * 任命就是往字典里写一个键，兴修就是花粮加一，遣使永远 +18。
 * 天下没有任何东西会拒绝他 —— 于是每一步都不是决策，只是点。
 *
 * 而且这盘棋**只能输，不能赢**：`EndingKind` 里三条全是败法，
 * 没有一行代码定义过「赢」。玩家打到腻了就关掉，仅此而已。
 *
 * ── 这一层怎么治 ────────────────────────────────────
 *
 * 一、**主公不再有按钮，他只有答复。**
 *    事情由帐下的人呈上来（见 Memorial），你批。
 *    兴修不是你点的，是有人请你拨粮；出兵不是你点的，是有人请战。
 *
 * 二、**人有心气，而心气是暗的。**
 *    你允了他的事就涨，驳了就跌，久不理会也跌。
 *    但你永远看不到那个数 —— 你只看得到他说话的口气。
 *    心气到底的人**不再上报**：他已经决定自己看着办了。
 *    所以案头空了不是太平，是出事了。
 *
 * 三、**主公会死，而赢不是你点的。**
 *    寿数是暗的。要走到「开国」，得凑齐土、名、人三样，
 *    而其中两样跟打仗无关 —— 尤其最后一样：
 *    **得有人肯替你上那道劝进表**。你一辈子怎么待人，最后决定有没有人推你上去。
 */
import type { NodeId } from './world_types.ts';

